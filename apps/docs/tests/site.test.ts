  await page.getByRole('link', { name: '插件管理', exact: true }).click();
  // 独立包页签只调用框架管理器，实际挂载／刷新／卸载均走浏览器安装库。
  await page.getByRole('button', { name: '独立插件包', exact: true }).click();
  const content = { formatVersion: 1, name: 'docs-external-example', declaration: { formatVersion: 1,
    manifest: { id: 'docs.external-example', version: '1.0.0', apiVersion: '^1', requires: [], provides: [] },
    entries: { browser: 'dist/browser.js' }, assets: {}, shared: [] },
    code: `export default manifest=>({manifest,prepare:()=>({ok:true,value(scope){const node=document.createElement('output');node.id='external-check';node.textContent='外部插件已运行';document.body.append(node);scope.onDispose(()=>node.remove())}})})`, assets: {} };
