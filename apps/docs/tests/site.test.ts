  const recoveryContext = await browser.newContext(); const recovery = await recoveryContext.newPage();
  await recovery.goto(server.url);
  await recovery.locator('.markdown-content h1').waitFor();
  await recovery.route('**/search.json', route => route.fulfill({ status: 503, body: 'unavailable' }));
  await recovery.getByRole('button', { name: /搜索文档/ }).click();
  await recovery.getByRole('alert').filter({ hasText: '搜索索引读取失败' }).waitFor();
  await recovery.getByRole('button', { name: '关闭', exact: true }).click();
