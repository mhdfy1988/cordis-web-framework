  await page.screenshot({ path: 'output/npm-manager-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'output/npm-manager-mobile.png', fullPage: true });
  await row.getByRole('button', { name: '卸载', exact: true }).click(); await page.getByRole('button', { name: '确认卸载', exact: true }).click();
  await row.waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('button', { name: '应用插件', exact: true }).click();
