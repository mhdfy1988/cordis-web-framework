  await page.keyboard.press('Escape');
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('dialog[open]').count(), 0);
  assert.equal(await page.locator('.search-trigger').evaluate(element => element === document.activeElement), true);
  await page.keyboard.press('Control+k');
  await page.locator('dialog[open]').waitFor();
  await page.locator('#document-search').fill('zzzzzznotfound');
  await page.getByText('没有找到相关文档', { exact: true }).waitFor();
  await page.locator('#document-search').fill('插件');
  await page.locator('dialog nav a').first().click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('dialog[open]').count(), 0);
  await page.locator('.markdown-content h1').waitFor();
  await page.locator('.shell-navigation a[href="#/guide/plugins"]').click();
  await page.waitForFunction(() => document.title.startsWith('编写第一个插件'));
  const copy = page.getByRole('button', { name: '复制代码', exact: true }).first();
  await copy.focus(); await copy.click();
  await page.getByText('已复制代码', { exact: true }).waitFor();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(copied.length > 20);
  const outline = page.locator('.shell-aside a').last();
  const sectionUrl = await outline.getAttribute('href');
  await outline.click();
  assert.ok(page.url().includes('section='));
  await page.reload();
  await page.locator('.markdown-content h1').waitFor();
  const headingTop = await page.evaluate(() => {
    const section = new URLSearchParams(location.hash.split('?')[1]).get('section')!;
    return document.getElementById(section)?.getBoundingClientRect().top;
  });
  assert.ok(headingTop !== undefined && headingTop >= 64 && headingTop < 960, `锚点没有进入可见区 ${headingTop} ${sectionUrl}`);
  await page.locator('.shell-brand').click();
  await page.waitForFunction(() => document.title.startsWith('Cordis Web Framework'));
  await page.goBack();
  await page.waitForFunction(() => document.title.startsWith('编写第一个插件'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '章节', exact: true }).click();
  await page.locator('.shell-navigation.open').waitFor();
  await page.locator('.shell-navigation a[href="#/guide/getting-started"]').click();
