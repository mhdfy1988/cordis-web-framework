  await recovery.getByRole('button', { name: /搜索文档/ }).click();
  await recovery.locator('#document-search').fill('插件');
  await recovery.locator('dialog nav a').first().waitFor();
  assert.equal(await recovery.getByRole('alert').count(), 0);
  await recoveryContext.close();
  console.log('框架主界面已呈现');
  for (const document of manifest.pages) {
    await page.goto(server.url + '#' + document.route);
    await page.waitForFunction(title => document.title.startsWith(title), document.title);
    await page.locator('.markdown-content h1').waitFor();
    assert.equal(await page.locator('.document-error').count(), 0);
  }
  console.log(`全量 ${manifest.pages.length} 页已加载`);
  await page.goto(server.url);
  await page.locator('.markdown-content h1').waitFor();
  await page.screenshot({ path: 'output/documentation-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '切换深浅色主题' }).click();
  await page.waitForFunction(() => document.querySelector('#app')?.getAttribute('data-theme') === 'dark');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#app')?.getAttribute('data-theme') === 'dark');
