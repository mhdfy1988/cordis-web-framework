  assert.equal(shutdown.shutdown.state, 'stopped');
  assert.deepEqual(shutdown.shutdown.runtime.plugins.map((item: { id: string }) => item.id).sort(), ['docs.foundation', 'docs.content', 'docs.clipboard', 'docs.content-view', 'docs.navigation', 'docs.outline', 'docs.management', 'docs.theme-control', 'docs.search', 'docs.header', 'ui.default-layout', 'ui.default-theme'].sort());
